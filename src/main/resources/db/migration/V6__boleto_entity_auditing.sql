CREATE TABLE boleto_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revised_at BIGINT NOT NULL,
    actor TEXT NOT NULL,
    correlation_id VARCHAR(36) NOT NULL
);

CREATE TABLE boleto_revision_state (
    id UUID NOT NULL,
    rev BIGINT NOT NULL REFERENCES boleto_revision(id),
    revtype SMALLINT NOT NULL,
    amount NUMERIC(8, 2),
    due_date DATE,
    issued_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(16),
    version BIGINT,
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    created_by TEXT,
    updated_by TEXT,
    PRIMARY KEY (id, rev)
);
